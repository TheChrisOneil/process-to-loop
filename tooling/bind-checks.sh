#!/usr/bin/env bash
# Bind a run's checks to its values, once, at the start of the run.
#
#   bind-checks.sh [--checks "a b c"] <artifact_root> <checks_dir> KEY=VALUE ...
#
# A formula declares [vars] at cook time. An exec check needs those values at run
# time, and gc passes it only GC_BEAD_ID. Recovering them at run time means a
# check that needs gc on PATH, a reachable bead store, a cwd inside a city tree
# and a login-shell environment — four dependencies, each of which failed at
# least once in the week of 2026-10-02, every time reporting something else.
#
# So bind them here instead. Each emitted wrapper exports its values literally
# and execs the real check. The result needs nothing but a filesystem, which is
# the same property emit-bundle.sh already gives the RPA it produces.
#
# Exit 0  every wrapper written and executable
# Exit 1  a named check is missing, so nothing was written
# Exit 64 wrong arguments
set -uo pipefail
# Which checks to bind. design-authoring's set is the default because it was the
# first caller; check-authoring passes its own. A formula whose checks are not
# bound reaches its gates with nothing in the environment, which is how
# check-authoring failed on its first run: both of its gates reported "not set"
# and neither had anything to do with the script being judged.
CHECKS="design-reviewed design-validate design-audited diagrams-complete bundle-records prior-archived questions-asked questions-answered"
case "${1:-}" in --checks) CHECKS=${2:-}; shift 2 ;; esac
R=${1:?artifact_root}; C=${2:?checks_dir}; shift 2
[ -d "$R" ] || { echo "no artifact_root at $R" >&2; exit 64; }
[ -d "$C" ] || { echo "no checks directory at $C" >&2; exit 64; }

MISSING=""
for n in $CHECKS; do [ -f "$C/$n.sh" ] || MISSING="$MISSING $n"; done
[ -z "$MISSING" ] || { echo "REFUSED: these checks are not in $C:$MISSING" >&2
  echo "         Nothing was written. A missing check is a gate that would not run." >&2; exit 1; }

# Each check declares the values it must be handed, on a "# requires:" line.
# Without this the omission is discovered at run time by the check itself, which
# can only report "could not run" — and gc has no outcome for that, so it
# surfaces as a failed gate with a reason about the environment rather than the
# artifact. AUDIT_SUBJECT was left out of check-authoring's binding on
# 2026-10-14 and two runs reported a failed audit for a gate that never ran.
SUPPLIED=" $(for kv in "$@"; do printf '%s ' "${kv%%=*}"; done)"
UNMET=""
for n in $CHECKS; do
  req=$(sed -n 's/^# requires:[[:space:]]*//p' "$C/$n.sh" | head -1)
  [ -n "$req" ] || continue
  for v in $req; do
    case "$SUPPLIED" in *" $v "*) ;; *) UNMET="$UNMET $n:$v" ;; esac
  done
done
if [ -n "$UNMET" ]; then
  echo "REFUSED: the binding omits values these checks require:$UNMET" >&2
  echo "         Nothing was written. A check that learns at run time that a value is" >&2
  echo "         missing can only say it could not run, and that reads as a failed gate." >&2
  echo "         Next human action: pass each NAME=VALUE above to bind-checks.sh." >&2
  exit 1
fi

OUT="$R/checks"
mkdir -p "$OUT" || { echo "could not create $OUT" >&2; exit 1; }

# Build the export block once, quoting every value so a path with a space or a
# quote cannot change what the wrapper does.
EXPORTS=$(for kv in "$@"; do
  k=${kv%%=*}; v=${kv#*=}
  [ -n "$k" ] || continue
  printf "export %s='%s'\n" "$k" "$(printf '%s' "$v" | sed "s/'/'\\\\''/g")"
done)

for n in $CHECKS; do
  W="$OUT/$n.sh"
  {
    echo "#!/usr/bin/env bash"
    echo "# Generated by bind-checks.sh for this run. Do not edit."
    echo "# Every value below was known when the formula was cooked. Binding them"
    echo "# here means this check needs no gc, no bead store, no particular cwd and"
    echo "# no login-shell environment to find its own inputs."
    echo "set -uo pipefail"
    echo "$EXPORTS"
    printf "exec '%s' \"\$@\"\n" "$C/$n.sh"
  } > "$W"
  chmod +x "$W" || { echo "could not make $W executable" >&2; exit 1; }
done

# A manifest of what was bound, so the gate that verifies the binding reads this
# rather than carrying its own copy of the list. Two hardcoded lists drift, and
# the one that drifts silently is the verifier.
: > "$OUT/.bound"
for n in $CHECKS; do printf '%s\n' "$n" >> "$OUT/.bound"; done

echo "bound $(echo $CHECKS | wc -w | tr -d ' ') check(s) into $OUT, against $C"
echo "values: $(for kv in "$@"; do printf '%s ' "${kv%%=*}"; done)"
